def main(dst):
    rnd = random.Random(1986)
    out = {}
    for cat, items in CATS.items():
        seen = set(); out[cat] = {"200": [], "400": [], "600": []}
        for lvl, q, a, wrong, src in items:
            assert q not in seen, q; seen.add(q)
            assert a not in wrong and len(set(wrong)) == len(wrong) == 3, q
            opts = [a] + wrong; rnd.shuffle(opts)
            out[cat][lvl].append([q, opts, opts.index(a)])
        print(cat, {k: len(v) for k, v in out[cat].items()}, len(items), "OpenTDB:", sum(i[4] == "o" for i in items))
    json.dump(out, open(dst, "w"), ensure_ascii=False, indent=0)

