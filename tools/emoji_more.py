def grab(s, name):
    m = re.search(r'const ' + name + r'=(\{.*?\});\n', s)
    return m, json.loads(m.group(1))

def put(s, m, obj):
    return s[:m.start(1)] + json.dumps(obj, ensure_ascii=False, separators=(',', ':')) + s[m.end(1):]

def apply(path):
    s = open(path).read()
    m, B = grab(s, 'BANK')
    seen = {q[0].split('|')[1] for k in EMO if k in B for L in B[k].values() for q in L}
    answers = {(k, q[1]) for k in EMO if k in B for L in B[k].values() for q in L}
