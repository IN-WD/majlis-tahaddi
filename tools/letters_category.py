def main(html, dst):
    h = open(html).read()
    i = h.index("const BANK=") + len("const BANK="); j = h.index(";\n", i); bank = json.loads(h[i:j])
    rnd = random.Random(5)
    out = {"200": [], "400": [], "600": []}; per = collections.Counter(); seen = set()
    for cat in SRC:
        for lvl, items in bank.get(cat, {}).items():
            for x in items:
                if isinstance(x[1], list): ans = x[1][x[2]]
                else: ans = x[1]
                ans = str(ans).strip().rstrip(".،")
                if re.search(r"[0-9٠-٩]", ans) or len(ans) > 22 or len(ans.split()) > 3: continue
                if re.search(r"(جميع|كل|لا شيء|صح|خطأ|نعم|^لا$)", ans): continue
                if re.search(r"[+A-Za-z/]", ans) or not re.search(r"[؟?]\s*$", x[0]): continue
                if re.search(r"(^\s*[:\-.]|\.\.|…|ــ|الآتية|التالية|التالي|يلي|مما سبق|[ٌٍ])", x[0]) or len(x[0]) > 110: continue
                L = first_letter(ans)
                if not L or x[0] in seen: continue
                seen.add(x[0])
                q = f"حرف «{L}»: {x[0]}"
                if isinstance(x[1], list):
                    opts = [str(o).strip().rstrip(".،") for o in x[1]]
                    out[lvl].append([q, opts, x[2]] + ([x[3]] if len(x) > 3 else []))
                else:
                    out[lvl].append([q, ans])
                per[L] += 1
    bad = []
    for lvl, L, q, a in EXTRA + HARD:
        if first_letter(a) != L: bad.append((L, a)); continue
        if q in seen: continue
        seen.add(q); out[lvl].append([f"حرف «{L}»: {q}", a]); per[L] += 1
    if bad: print("LETTER MISMATCH:", bad)
    json.dump({"huroof": out}, open(dst, "w"), ensure_ascii=False, indent=0)
    print({p: len(v) for p, v in out.items()}, "total", sum(per.values()))
    print(" ".join(f"{l}:{per[l]}" for l in "أ" + AR_LET[1:]))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
