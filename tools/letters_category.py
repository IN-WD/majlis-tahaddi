def first_letter(ans):
    a = ans.strip().strip("«»\"'()")
    a = re.sub(r"^(ال)(?=\S{2,})", "", a)
    if not a: return None
    c = a[0]
    if c in "أإآا": return "أ"
    if c == "ة": return None
    return c if c in AR_LET else None

