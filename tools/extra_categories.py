def mcq(q, correct, pool, n=4):
    opts = [correct]
    for x in rnd.sample(pool, len(pool)):
        if x != correct and x not in opts:
            opts.append(x)
        if len(opts) == n: break
    rnd.shuffle(opts)
    return [q, opts, opts.index(correct)]

