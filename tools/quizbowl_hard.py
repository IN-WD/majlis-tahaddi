def norm(s):
    return re.sub(r'[\sً-ْ«»()،؟?.]', '', s).replace('أ','ا').replace('إ','ا').replace('ة','ه')

def apply(path):
    s = open(path).read()
    m = re.search(r'const BANK=(\{.*?\});\n', s)
    B = json.loads(m.group(1))
    have = {norm(q[0]) for k in B for L in B[k].values() for q in L}
    ans600 = {(k, norm(str(q[1]))) for k in B for q in B[k]["600"]}
    added = skipped = 0
    for pid, cat, q, a, ctx in Q:
        if norm(q) in have or (cat, norm(a)) in ans600:
            skipped += 1; continue
        note = (ctx + " — " if ctx else "") + SRC
        B[cat]["600"].append([q, a, note]); have.add(norm(q)); added += 1
    s = s[:m.start(1)] + json.dumps(B, ensure_ascii=False, separators=(',', ':')) + s[m.end(1):]
    open(path, 'w').write(s)
    print(path, 'added', added, 'skipped', skipped, {k: len(B[k]["600"]) for k in ["sci","tec","his","geo","gk"]})

if __name__ == "__main__":
    ids = [x[0] for x in Q]; assert len(ids) == len(set(ids))
    for p in sys.argv[1:]:
        apply(p)
