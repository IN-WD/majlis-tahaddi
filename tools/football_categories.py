import json, random, sys

rnd = random.Random(7)
AR = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")
def ar(x): return str(x).translate(AR)
def mcq(q, correct, pool, n=4):
    opts = [correct] + [x for x in rnd.sample(pool, len(pool)) if x != correct]
    opts = list(dict.fromkeys(opts))[:n]; rnd.shuffle(opts)
    return [q, opts, opts.index(correct)]
def season_ar(s):  # '2015-16' -> '٢٠١٥–٢٠١٦'
    a = int(s[:4]); return ar(f"{a}–{a+1}")

