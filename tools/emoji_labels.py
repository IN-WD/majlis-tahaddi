for p in sys.argv[1:]:
    s = open(p).read()
    m = re.search(r'const BANK=(\{.*?\});\n', s)
    B = json.loads(m.group(1))
    n = 0
    for k in ['emp', 'emf', 'ema', 'emo']:
        for lv, qs in B[k].items():
            for i, q in enumerate(qs):
                lab = 'مثل' if k == 'emo' else L[k][lv][i]
                parts = q[0].split('|')
                q[0] = '|'.join(parts[:2] + [lab]); n += 1
    s = s[:m.start(1)] + json.dumps(B, ensure_ascii=False, separators=(',', ':')) + s[m.end(1):]
    old = 'if(isPic)$("mPic").textContent=q.q.slice(q.q.indexOf("|")+1);'
    new = 'const pp=isPic?q.q.split("|"):[];if(isPic)$("mPic").textContent=pp[1];'
    old2 = '$("mQ").textContent=isPic?"خمن من الإيموجي":q.q;'
    new2 = '$("mQ").textContent=isPic?(pp[2]?"🎯 خمّن: "+pp[2]:"خمن من الإيموجي"):q.q;'
    if old in s:
        s = s.replace(old, new).replace(old2, new2)
    open(p, 'w').write(s); print(p, n)
